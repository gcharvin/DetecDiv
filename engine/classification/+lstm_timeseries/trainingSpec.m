function spec = trainingSpec(classif)
if nargin<1,classif=[];end
p=lstm_timeseries.parameters(classif);
spec=repmat(classifierBinding.newBinding(),0,1);
for k=1:p.featureCount
    spec(end+1)=classifierBinding.newBinding('param',sprintf('feature%d',k), ...
        'type','dataSeriesVariable','role','numeric_trace','required',true, ...
        'label',sprintf('[INPUT] Numeric trace %d',k),'quality','input', ...
        'storage','packageInputs','editable',false,'semantic','numeric_temporal_feature', ...
        'tip','Configured in Pipeline2: select the dataseries, variable and, only for vector variables, a component.'); %#ok<AGROW>
end
spec(end+1)=classifierBinding.newBinding('param','groundTruthLabels','type','dataseries', ...
    'role','frame_label_ground_truth','quality','gt','label','[GT] Reviewed state labels', ...
    'required',true,'storage','annotation','editable',false,'componentId','labels');
end
