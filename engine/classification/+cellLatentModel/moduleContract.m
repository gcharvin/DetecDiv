function contract = moduleContract(params)
%CELLLATENTMODEL.MODULECONTRACT Pure semantic patch for classifier nodes.
% The contract describes the effective node parameters without resolving a
% runtime, reading model artifacts, or changing classifier/ROI data. Missing
% backend parameters deliberately retain the legacy saved-pipeline default.
if nargin < 1 || isempty(params), params = struct(); end

backend = normalizeChoice(paramValue(params, 'backend', 'legacy'), ...
    {'causal_composite','legacy','temporal_lineage','continuous_cell_state'}, 'legacy');
temporalVariant = normalizeChoice(paramValue(params, 'temporalVariant', 'temporal_geometry'), ...
    {'temporal_geometry','all_observed'}, 'temporal_geometry');
stateUpdateMode = normalizeChoice(paramValue(params, 'stateUpdateMode', 'none'), ...
    {'none','promoted_frozen_bf'}, 'none');
spec = cellLatentModel.executionSpec();
semanticKeys = {'backend','temporalVariant','frameIntervalMinutes', ...
    'causalSolverFeedback','materializeCellStates','primaryStateAxis', ...
    'statePositiveThreshold','stateNegativeThreshold'};

contract = struct();
contract.format = 'detecdiv.module_contract.v1';
contract.in = portDef('roiList', 'roiList', true);
contract.out = [ ...
    portDef('roiList', 'roiList', true), ...
    portDef('dataSeries', 'dataSeriesSet', true), ...
    portDef('objects', 'cellObjectSet', true) ...
    ];
contract.parameters.static = unique([semanticKeys normalizeCellstr(spec.staticKeys)], 'stable');
contract.requirements.roi.channelsMin = 1;
contract.capabilities = struct( ...
    'outputsMasks', false, 'outputsChannels', false, ...
    'roiMasks', false, 'roiChannels', false, ...
    'roiDataSeries', true, 'outputsDataSeries', true);
contract.binding = struct( ...
    'scope', 'roi', 'outputScope', 'roi', 'mode', 'channelSlots', ...
    'resolveAt', 'run', 'minCount', 1, 'exactCount', [], 'defaultCount', []);
contract.selectors = struct( ...
    'channelParam', 'trackChannelName', 'channelsParam', '', ...
    'framesParam', '', 'outputNameParam', 'outputFamilyName');
contract.resources.in = resourceDef('channel', 'mask_roi_image', ...
    'tracked_masks', 'trackChannelName', 'channels', 'trackChannelName', true, '');
contract.semantics = struct('inputIdentity', 'stable_tracks', ...
    'outputIdentity', 'stable_tracks');

if strcmp(backend, 'causal_composite')
    contract.capabilities.outputsChannels = true;
    contract.capabilities.roiChannels = true;
    contract.binding.selectorKeys = {'instanceChannelName', ...
        'brightfieldChannelName','nucleusChannelName','budneckChannelName'};
    contract.selectors.channelParam = 'instanceChannelName';
    contract.resources.in = [ ...
        resourceDef('channel','mask_roi_image','frame_local_instances', ...
            'instanceChannelName','channels','instanceChannelName',true,''), ...
        resourceDef('channel','brightfield_image','brightfield_image', ...
            'brightfieldChannelName','channels','brightfieldChannelName', ...
            strcmp(stateUpdateMode,'promoted_frozen_bf'),''), ...
        resourceDef('channel','division_nucleus_fluorescence', ...
            'division_nucleus_fluorescence','nucleusChannelName', ...
            'channels','nucleusChannelName',false,''), ...
        resourceDef('channel','bud_neck_fluorescence','bud_neck_fluorescence', ...
            'budneckChannelName','channels','budneckChannelName',false,'') ...
        ];
    contract.out(end+1) = portDef('channels','channelSet',true);
    contract.semantics.inputIdentity = 'frame_local_instances';
elseif strcmp(backend, 'legacy')
    contract.binding.selectorKeys = {'trackChannelName','gfpChannelName'};
    contract.resources.in(end+1) = resourceDef('channel', 'legacy_gfp_fluorescence', ...
        'legacy_gfp_fluorescence', 'gfpChannelName', 'channels', ...
        'gfpChannelName', false, '');
elseif strcmp(backend, 'continuous_cell_state')
    contract.binding.selectorKeys = {'trackChannelName','brightfieldChannelName', ...
        'nucleusChannelName','budneckChannelName'};
    contract.resources.in(end+1) = resourceDef('channel', 'brightfield_image', ...
        'brightfield_image', 'brightfieldChannelName', 'channels', ...
        'brightfieldChannelName', false, '');
    contract.resources.in(end+1) = resourceDef('channel', 'division_nucleus_fluorescence', ...
        'division_nucleus_fluorescence', 'nucleusChannelName', 'channels', ...
        'nucleusChannelName', false, '');
    contract.resources.in(end+1) = resourceDef('channel', 'bud_neck_fluorescence', ...
        'bud_neck_fluorescence', 'budneckChannelName', 'channels', ...
        'budneckChannelName', false, '');
elseif strcmp(temporalVariant, 'all_observed')
    contract.binding.selectorKeys = {'trackChannelName','nucleusChannelName','budneckChannelName'};
    contract.resources.in(end+1) = resourceDef('channel', 'division_nucleus_fluorescence', ...
        'division_nucleus_fluorescence', 'nucleusChannelName', 'channels', ...
        'nucleusChannelName', false, '');
    contract.resources.in(end+1) = resourceDef('channel', 'bud_neck_fluorescence', ...
        'bud_neck_fluorescence', 'budneckChannelName', 'channels', ...
        'budneckChannelName', false, '');
else
    contract.binding.selectorKeys = {'trackChannelName'};
end

lineageOutputs = [ ...
    resourceDef('dataSeries', 'lineage', 'cell_latent_lineage', ...
        'outputFamilyName', 'dataSeries', 'outputFamilyName', false, 'roiDataSeries'), ...
    resourceDef('cellModel', 'cellular_objects', 'cell_latent_objects', ...
        'outputFamilyName', 'objects', 'outputFamilyName', false, 'roiCellModel') ...
    ];
if strcmp(backend, 'causal_composite')
    contract.resources.out = [ ...
        resourceDef('channel','tracking','predicted_tracks', ...
            'outputTrackChannelName','channels','outputTrackChannelName',false,'roiChannel'), ...
        lineageOutputs ...
        ];
else
    contract.resources.out = lineageOutputs;
end
% executionSpec historically supplies the final pipeline summary.
contract.summary = spec.summary;
end

function value = paramValue(params, name, defaultValue)
value = defaultValue;
if isstruct(params) && isfield(params, name) && ~isempty(params.(name))
    value = params.(name);
end
end

function mode = normalizeChoice(value, allowed, defaultValue)
mode = lower(strtrim(choiceToChar(value)));
mode = strrep(mode, '-', '_');
mode = strrep(mode, ' ', '_');
if isempty(mode) || ~any(strcmp(mode, allowed)), mode = defaultValue; end
end

function txt = choiceToChar(value)
txt = '';
if isempty(value), return; end
if iscell(value)
    flat = value(~cellfun(@isempty, value));
    if ~isempty(flat), txt = char(string(flat{end})); end
elseif ischar(value)
    txt = value;
elseif isstring(value) || isnumeric(value) || islogical(value) || iscategorical(value)
    vals = string(value(:));
    if ~isempty(vals), txt = char(vals(end)); end
else
    try
        txt = char(string(value));
    catch
        txt = '';
    end
end
end

function list = normalizeCellstr(value)
list = {};
if isempty(value), return; end
if ischar(value) || isstring(value)
    list = cellstr(string(value(:)));
    list = list(~cellfun(@(x) isempty(strtrim(x)), list));
elseif iscell(value)
    for i = 1:numel(value)
        if isempty(value{i}), continue; end
        try
            list{end+1} = char(string(value{i})); %#ok<AGROW>
        catch
        end
    end
    list = list(~cellfun(@(x) isempty(strtrim(x)), list));
end
end

function port = portDef(name, type, required)
port = struct('name', name, 'type', type, 'required', logical(required), 'source', 'edge');
end

function resource = resourceDef(type, role, symbol, param, port, nameParam, required, transfer)
resource = struct('type', type, 'role', role, 'symbol', symbol, 'param', param, ...
    'port', port, 'nameParam', nameParam, 'required', logical(required), 'transfer', transfer);
end
