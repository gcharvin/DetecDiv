function scanValue(value, forbidden, location)
if isstruct(value)
    names = fieldnames(value);
    for row = 1:numel(value)
        for i = 1:numel(names)
            assertNoForbiddenToken(names{i}, forbidden, location);
            scanValue(value(row).(names{i}), forbidden, ...
                [location '.' names{i}]);
        end
    end
elseif iscell(value)
    for i = 1:numel(value)
        scanValue(value{i}, forbidden, location);
    end
elseif ischar(value) || isstring(value)
    values = string(value);
    for i = 1:numel(values)
        assertNoForbiddenToken(char(values(i)), forbidden, location);
    end
end
end

function assertNoForbiddenToken(value, forbidden, location)
value = lower(char(string(value)));
for i = 1:numel(forbidden)
    if contains(value, forbidden{i})
        error('cellLatentModel:BenchmarkInputLeakage', ...
            'Forbidden inference token "%s" at %s.', forbidden{i}, location);
    end
end
end

function assertInferenceDirectoryClean(folder)
