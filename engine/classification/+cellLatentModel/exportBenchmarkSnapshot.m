value = char(datetime('now', 'TimeZone', 'UTC', ...
    'Format', 'yyyy-MM-dd''T''HH:mm:ss.SSSXXX'));
end

function removeFolder(folder)
if isfolder(folder)
    try rmdir(folder, 's'); catch, end
end
end
