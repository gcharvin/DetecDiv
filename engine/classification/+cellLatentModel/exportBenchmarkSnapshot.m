row = struct('roi_id','','partition','','source_frames',[], ...
    'frame_bounds',[],'payload_path','','payload_sha256','', ...
    'payload_bytes',0,'relation_namespace',struct(), ...
    'stable_id_dataset','','lifecycle_datasets',struct(), ...
    'relation_datasets',struct(),'track_count',0,'parent_count',0, ...
    'null_count',0,'end_count',0,'approval',struct(), ...
    'label_quality','');
end

function value = inferenceClassifierProvenance(classif, file)
value = struct( ...
    'id', char(string(classif.strid)), ...
    'snapshot_sha256', file.sha256, ...
    'snapshot_bytes', file.bytes);
end

function values = inferenceRoiProvenance(rois)
values = repmat(struct('roi_index',0,'roi_id','','roi_bbox',[], ...
    'source_sha256','','image_store_sha256',''), numel(rois), 1);
for i = 1:numel(rois)
    values(i) = struct( ...
        'roi_index', rois(i).roi_index, ...
        'roi_id', rois(i).roi_id, ...
        'roi_bbox', rois(i).roi_bbox, ...
        'source_sha256', rois(i).source_sha256, ...
        'image_store_sha256', rois(i).image_store_sha256);
end
end

function split = normalizeSplit(classif, raw)
if ~isstruct(raw) || ~isscalar(raw)
    error('cellLatentModel:InvalidBenchmarkSplit', ...
        'Split must be a scalar struct with train/validation/test indices.');
end
train = splitValues(raw, {'train'});
validation = splitValues(raw, {'validation','val'});
test = splitValues(raw, {'test'});
allIndices = [train validation test];
if any(allIndices < 1 | allIndices > numel(classif.roi)) || ...
        numel(unique(allIndices)) ~= numel(allIndices)
    error('cellLatentModel:InvalidBenchmarkSplit', ...
        ['Split ROI indices must be in range and each ROI must belong to ' ...
         'exactly one partition.']);
end
allIds = roiIds(classif, allIndices);
if any(cellfun(@isempty, allIds)) || ...
        numel(unique(lower(string(allIds)))) ~= numel(allIds)
    error('cellLatentModel:InvalidBenchmarkSplit', ...
        'Every exported ROI must have one non-empty unique stable ROI ID.');
end
allPaths = strings(1, numel(allIndices));
for i = 1:numel(allIndices)
    source = classif.roi(allIndices(i));
    roiId = char(string(source.id));
    imageStore = fullfile(source.path, ['im_' roiId '.h5']);
    if ~isfile(imageStore)
        error('cellLatentModel:InvalidBenchmarkSplit', ...
            ['ROI identity "%s" does not resolve to its authoritative ' ...
             'image store: %s. Aliases cannot cross benchmark partitions.'], ...
            roiId, imageStore);
    end
    allPaths(i) = lower(string(canonicalPath(imageStore)));
end
if numel(unique(allPaths)) ~= numel(allPaths)
    error('cellLatentModel:InvalidBenchmarkSplit', ...
        ['The same disk-backed ROI source appears more than once in the ' ...
         'split. A source cannot cross benchmark partitions under aliases.']);
end
split = struct( ...
    'train_indices', train, ...
    'validation_indices', validation, ...
    'test_indices', test, ...
    'train_ids', {roiIds(classif, train)}, ...
    'validation_ids', {roiIds(classif, validation)}, ...
    'test_ids', {roiIds(classif, test)});
end

function values = splitValues(raw, names)
values = [];
for i = 1:numel(names)
    if isfield(raw, names{i})
        values = raw.(names{i});
        break;
    end
end
if isempty(values), return; end
values = double(values(:).');
if any(~isfinite(values) | values ~= round(values))
    error('cellLatentModel:InvalidBenchmarkSplit', ...
        'Split ROI indices must be finite integers.');
end
values = round(values);
end

function ids = roiIds(classif, indices)
ids = cell(1, numel(indices));
for i = 1:numel(indices)
    ids{i} = char(string(classif.roi(indices(i)).id));
end
end

function partition = partitionForIndex(split, roiIndex)
if ismember(roiIndex, split.train_indices)
    partition = 'train';
elseif ismember(roiIndex, split.validation_indices)
    partition = 'validation';
elseif ismember(roiIndex, split.test_indices)
    partition = 'test';
else
    error('cellLatentModel:InvalidBenchmarkSplit', ...
        'ROI %d is not assigned to the benchmark split.', roiIndex);
end
end

function value = inputSplit(split)
value = struct('train', {split.train_ids}, ...
    'validation', {split.validation_ids}, 'test', {split.test_ids});
end

function value = targetSplit(split)
value = inputSplit(split);
end

function value = topSplit(split)
value = struct( ...
    'unit', 'whole_roi', ...
    'train', struct('indices', split.train_indices, ...
        'roi_ids', {split.train_ids}), ...
    'validation', struct('indices', split.validation_indices, ...
        'roi_ids', {split.validation_ids}), ...
    'test', struct('indices', split.test_indices, ...
        'roi_ids', {split.test_ids}), ...
    'overlap_allowed', false);
end

function roiObj = detachedDiskRoi(source, channels)
[h5File, exists] = source.getH5Filename();
if ~exists
    error('cellLatentModel:BenchmarkSourceNotMaterialized', ...
        'ROI %s has no disk-backed HDF5 source: %s', ...
        char(string(source.id)), h5File);
end
roiObj = roi(char(string(source.id)), source.value);
roiObj.path = char(string(source.path));
try
    roiObj.load('Channel', unique(channels, 'stable'), ...
        'Data', true, 'Silent');
catch ME
    error('cellLatentModel:BenchmarkChannelNotFound', ...
        'Cannot load required ROI %s benchmark channel(s): %s', ...
        char(string(source.id)), ME.message);
end
end

function stack = readSinglePlaneStack(roiObj, channelName, labels)
try
    index = roiObj.findChannelID(channelName, 'exact');
catch
    index = roiObj.findChannelID(channelName);
end

if numel(index) ~= 1
    error('cellLatentModel:BenchmarkChannelNotFound', ...
        ['ROI %s must contain exactly one image plane for channel "%s"; ' ...
         'found %d.'], char(string(roiObj.id)), channelName, numel(index));
end
stack = squeeze(roiObj.image(:,:,index,:));
if ismatrix(stack)
    stack = reshape(stack, size(stack,1), size(stack,2), 1);
end
if labels
    if any(~isfinite(double(stack(:))) | stack(:) < 0 | ...
            stack(:) ~= floor(stack(:)))
        error('cellLatentModel:InvalidBenchmarkMask', ...
            'ROI %s channel "%s" is not a non-negative integer mask.', ...
            char(string(roiObj.id)), channelName);
    end
    stack = uint32(stack);
else
    stack = single(stack);
end
end

function assertInputChannelRoles(roiObj, inputMaskName, brightfieldName)
maskIndexed = channelIndexedFlag(roiObj, inputMaskName);
rawIndexed = channelIndexedFlag(roiObj, brightfieldName);
if ~maskIndexed
    error('cellLatentModel:InvalidBenchmarkInputRole', ...
        'ROI %s input mask channel "%s" is not marked indexed.', ...
        char(string(roiObj.id)), inputMaskName);
end
if rawIndexed
    error('cellLatentModel:InvalidBenchmarkInputRole', ...
        ['ROI %s brightfield channel "%s" is marked indexed and may be ' ...
         'a label image. Select a genuine non-indexed raw channel.'], ...
        char(string(roiObj.id)), brightfieldName);
end
end

function value = channelIndexedFlag(roiObj, channelName)
try
    plane = roiObj.findChannelID(channelName, 'exact');
catch
    plane = roiObj.findChannelID(channelName);
end
if numel(plane) ~= 1
    error('cellLatentModel:BenchmarkChannelNotFound', ...
        'ROI %s channel "%s" does not resolve to one plane.', ...
        char(string(roiObj.id)), channelName);
end
logicalIndex = double(roiObj.channelid(plane));
if logicalIndex < 1 || logicalIndex > numel(roiObj.display.indexed)
    error('cellLatentModel:InvalidBenchmarkInputRole', ...
        'ROI %s channel "%s" has inconsistent indexed metadata.', ...
        char(string(roiObj.id)), channelName);
end
value = logical(roiObj.display.indexed(logicalIndex));
end

function assertCompatibleStacks(inputMasks, brightfield, gtMasks, roiId)
if ~isequal(size(inputMasks), size(brightfield)) || ...
        ~isequal(size(inputMasks), size(gtMasks))
    error('cellLatentModel:BenchmarkChannelSizeMismatch', ...
        ['ROI %s inference masks, brightfield and reviewed masks must have ' ...
         'identical H/W/T dimensions.'], char(string(roiId)));
end
end

function assertFramesAvailable(frames, total, roiId)
if isempty(frames) || any(frames < 1 | frames > total) || ...
        any(diff(frames) ~= 1)
    error('cellLatentModel:InvalidBenchmarkFrameBounds', ...
        ['ROI %s benchmark frames must be one non-empty contiguous range ' ...
         'within 1:%d.'], char(string(roiId)), total);
end
end

function frames = approvedFrames(approval, roiObj)
bounds = double(approval.frame_bounds(:).');
if numel(bounds) ~= 2 || any(~isfinite(bounds)) || ...
        bounds(1) < 1 || bounds(2) < bounds(1)
    error('cellLatentModel:InvalidBenchmarkFrameBounds', ...
        'ROI %s approval has invalid frame bounds.', char(string(roiObj.id)));
end
frames = round(bounds(1)):round(bounds(2));
end

function masks = canonicalFrameLocalLabels(masks)
masks = uint32(masks);
for frame = 1:size(masks, 3)
    source = masks(:,:,frame);
    labels = unique(source);
    labels(labels == 0) = [];
    target = zeros(size(source), 'uint32');
    for i = 1:numel(labels)
        target(source == labels(i)) = uint32(i);
    end
    masks(:,:,frame) = target;
end
end

function assertGroundTruthFamily(family, requested, roiId)
if ~strcmpi(char(string(family.name)), requested)
    error('cellLatentModel:BenchmarkGroundTruthFamilyMismatch', ...
        ['ROI %s reviewed mask provider resolves to family "%s", not the ' ...
         'requested GT family "%s".'], char(string(roiId)), ...
        char(string(family.name)), requested);
end
if ~strcmpi(char(string(family.lineage_source)), 'ground_truth')
    error('cellLatentModel:BenchmarkGroundTruthFamilyMismatch', ...
        'ROI %s family "%s" is not marked ground_truth.', ...
        char(string(roiId)), requested);
end
end

function assertInferenceChannelsNotGroundTruth( ...
        model, inputMaskName, brightfieldName, roiId)
model = cellModel.normalize(model);
families = model.families;
reviewed = strcmpi(string(families.lineage_source), 'ground_truth');
providers = string(families.mask_provider(reviewed));
roles = {inputMaskName, brightfieldName};
for i = 1:numel(roles)
    if any(strcmpi(providers, string(roles{i})))
        error('cellLatentModel:BenchmarkInputTargetCollision', ...
            ['ROI %s input channel "%s" is the mask provider of a ' ...
             'ground_truth cell-model family. Reviewed spatial labels ' ...
             'cannot enter the inference bundle under an alias.'], ...
            char(string(roiId)), roles{i});
    end
end
end

function target = buildTargets(model, family, stableIds, frames, ...
        roiFrameCount, roiId, approvalHash)
model = cellModel.normalize(model);
[model, ~] = cellModel.canonicalizeParentageEvents(model);
familyId = uint32(family.family_id);
materialized = unique(uint64(stableIds(stableIds > 0)));
if isempty(materialized)
    error('cellLatentModel:EmptyBenchmarkTarget', ...
        'ROI %s has no materialized stable GT identity.', ...
        char(string(roiId)));
end
instances = model.instances;
trackIds = unique(instances.track_id( ...
    instances.family_id == familyId & instances.track_id > 0));
if ~all(ismember(materialized, trackIds))
    error('cellLatentModel:InvalidBenchmarkTarget', ...
        'ROI %s materialized identities do not belong to the GT family.', ...
        char(string(roiId)));
end

trackIds = sort(materialized(:));
n = numel(trackIds);
birthSource = zeros(n,1,'uint32');
birthLocal = zeros(n,1,'uint32');
birthObserved = false(n,1);
endSource = zeros(n,1,'uint32');
endLocal = zeros(n,1,'uint32');
endObserved = false(n,1);
parentTrack = zeros(n,1,'uint64');
birthClass = zeros(n,1,'uint8'); % 0 censored, 1 NULL, 2 parent-linked

relationRows = find(model.relations.family_id == familyId & ...
    model.relations.type_id == uint8(1));
relations = repmat(struct('parent',uint64(0),'child',uint64(0), ...
    'event_source',uint32(0),'event_local',uint32(0)),0,1);
for i = 1:numel(relationRows)
    row = relationRows(i);
    child = model.relations.child_track_id(row);
    parent = model.relations.parent_track_id(row);
    if ~ismember(child, trackIds), continue; end
    if ~ismember(parent, trackIds)
        error('cellLatentModel:BenchmarkRelationOutsideNamespace', ...
            ['ROI %s relation child Track %u is selected but parent Track ' ...
             '%u is absent from the materialized target namespace.'], ...
            char(string(roiId)), child, parent);
    end
    sourceEvent = model.relations.event_frame(row);
    [present, localEvent] = ismember(double(sourceEvent), frames);
    if ~present
        error('cellLatentModel:BenchmarkRelationOutsideFrameBounds', ...
            ['ROI %s relation for selected child Track %u has event frame ' ...
             '%u outside the approved benchmark range %u:%u. Expand the ' ...
             'bounds rather than publishing an ambiguous local event.'], ...
            char(string(roiId)), child, sourceEvent, ...
            uint32(frames(1)), uint32(frames(end)));
    end
    relation = struct('parent',uint64(parent),'child',uint64(child), ...
        'event_source',uint32(sourceEvent), ...
        'event_local',uint32(localEvent));
    relations(end+1,1) = relation; %#ok<AGROW>
end
if numel(unique([relations.child])) ~= numel(relations)
    error('cellLatentModel:InvalidBenchmarkParentage', ...
        'ROI %s contains multiple selected parents for one child.', ...
        char(string(roiId)));
end

for i = 1:n
    id = trackIds(i);
    allFrames = unique(double(instances.frame( ...
        instances.family_id == familyId & instances.track_id == id)));
    globalBirth = min(allFrames);
    globalEnd = max(allFrames);
    birthSource(i) = uint32(globalBirth);
    endSource(i) = uint32(globalEnd);
    [birthInRange, localBirth] = ismember(globalBirth, frames);
    [endInRange, localEnd] = ismember(globalEnd, frames);
    birthLocal(i) = uint32(localBirth * birthInRange);
    endLocal(i) = uint32(localEnd * endInRange);
    birthObserved(i) = birthInRange && ...
        (globalBirth > frames(1) || frames(1) == 1);
    endObserved(i) = endInRange && globalEnd < frames(end) && ...
        globalEnd < double(roiFrameCount);

    match = find([relations.child] == id);
    if birthObserved(i)
        if isempty(match)
            birthClass(i) = uint8(1);
        else
            birthClass(i) = uint8(2);
            parentTrack(i) = relations(match).parent;
        end
    elseif ~isempty(match)
        error('cellLatentModel:BenchmarkRelationAtCensoredBirth', ...
            ['ROI %s relation for child Track %u falls in a left-censored ' ...
             'benchmark interval. Expand the approved frame bounds.'], ...
            char(string(roiId)), id);
    end
end

relationNamespace = struct( ...
    'schema', 'detecdiv.cell_model.roi_family_track_id.v1', ...
    'scope', 'roi_and_family', ...
    'namespace_id', namespaceId( ...
        roiId, family, frames, approvalHash), ...
    'roi_id', char(string(roiId)), ...
    'family_id', double(familyId), ...
    'family_name', char(string(family.name)), ...
    'mask_provider', char(string(family.mask_provider)), ...
    'lineage_source', char(string(family.lineage_source)), ...
    'approval_sha256', char(string(approvalHash)));
target = struct( ...
    'track_ids', trackIds, ...
    'birth_source', birthSource, ...
    'birth_local', birthLocal, ...
    'birth_observed', birthObserved, ...
    'end_source', endSource, ...
    'end_local', endLocal, ...
    'end_observed', endObserved, ...
    'parent_track', parentTrack, ...
    'birth_class', birthClass, ...
    'relations', relations, ...
    'relation_namespace', relationNamespace, ...
    'lifecycle_datasets', struct( ...
        'track_ids','/lifecycle/track_ids', ...
        'birth_source_frame','/lifecycle/birth_source_frame', ...
        'birth_local_frame','/lifecycle/birth_local_frame', ...
        'birth_observed','/lifecycle/birth_observed', ...
        'end_source_frame','/lifecycle/end_source_frame', ...
        'end_local_frame','/lifecycle/end_local_frame', ...
        'end_observed','/lifecycle/end_observed', ...
        'parent_track_id','/lifecycle/parent_track_id', ...
        'birth_class','/lifecycle/birth_class', ...
        'birth_class_legend',struct('censored',0,'null',1,'parent',2)), ...
    'relation_datasets', relationDatasetContract(relations));
end

