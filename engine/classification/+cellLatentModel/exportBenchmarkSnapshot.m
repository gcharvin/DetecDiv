row = struct('roi_id','','partition','','source_frames',[], ...
    'frame_bounds',[],'payload_path','','payload_sha256','', ...
    'payload_bytes',0,'mask_channel','','mask_dataset','', ...
    'mask_representation','','brightfield_channel','', ...
    'brightfield_dataset','');
end

