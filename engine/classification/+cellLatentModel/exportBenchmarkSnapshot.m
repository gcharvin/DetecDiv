function assertClassifierSnapshotMatches(classif, indices, filename)
try
    loaded = load(strrep(filename, '/', filesep), 'classiObj');
    saved = loaded.classiObj;
catch ME
    error('cellLatentModel:BenchmarkClassifierSnapshotMismatch', ...
        'Cannot read the saved classifier snapshot: %s', ME.message);
end
if ~isa(saved, 'classi') || ...
        ~strcmp(char(string(saved.strid)), char(string(classif.strid)))
    error('cellLatentModel:BenchmarkClassifierSnapshotMismatch', ...
        'The saved classifier does not match the active DetecDiv classifier.');
end
scientificProperties = {'classifierPkg','trainingParam','executionParam', ...
    'channelName','channelName2'};
for propertyIndex = 1:numel(scientificProperties)
    name = scientificProperties{propertyIndex};
    if ~isequaln(saved.(name), classif.(name))
        error('cellLatentModel:BenchmarkClassifierSnapshotMismatch', ...
            ['Active classifier property "%s" differs from the saved ' ...
             'snapshot. Save the classifier before exporting.'], name);
    end
end
savedIds = string({saved.roi.id});
for i = 1:numel(indices)
    currentIndex = indices(i);
    id = string(classif.roi(currentIndex).id);
    savedIndex = find(savedIds == id, 1);
    if isempty(savedIndex) || ...
            ~strcmpi(canonicalPath(saved.roi(savedIndex).path), ...
                canonicalPath(classif.roi(currentIndex).path)) || ...
            ~isequaln(double(saved.roi(savedIndex).value), ...
                double(classif.roi(currentIndex).value)) || ...
            ~isequal(effectiveBounds(saved, savedIndex), ...
                effectiveBounds(classif, currentIndex))
        error('cellLatentModel:BenchmarkClassifierSnapshotMismatch', ...
            ['ROI %s identity, source path or frame bounds differ from ' ...
             'the saved classifier. Save it before exporting; the exporter ' ...
             'will never call classiSave implicitly.'], id);
    end
end
end

