function snapshot = sourceSnapshot(classif, indices)
classifierFile = fullfile(classif.path, ...
    [char(string(classif.strid)) '_classification.mat']);
if ~isfile(classifierFile)
    error('cellLatentModel:BenchmarkSourceNotMaterialized', ...
        ['Classifier snapshot is missing: %s. Save the classifier before ' ...
         'creating an immutable benchmark export.'], classifierFile);
end
snapshot = struct('classifier_files', fileRecord(classifierFile), ...
    'rois', repmat(struct('roi_index',0,'roi_id','', ...
        'source_path','','roi_bbox',[],'files',struct([]), ...
        'source_sha256','', ...
        'image_store_sha256',''), ...
        numel(indices), 1));
for i = 1:numel(indices)
    source = classif.roi(indices(i));
    id = char(string(source.id));
    files = { ...
        fullfile(source.path, ['im_' id '.h5']), ...
        fullfile(source.path, ['objects_' id '.h5']), ...
        fullfile(source.path, ['data_' id '.mat'])};
    records = repmat(fileRecord(files{1}), 0, 1);
    for j = 1:numel(files)
        if ~isfile(files{j})
            error('cellLatentModel:BenchmarkSourceNotMaterialized', ...
                'ROI %s authoritative source is missing: %s', id, files{j});
        end
        records(end+1,1) = fileRecord(files{j}); %#ok<AGROW>
    end
    aggregate = strjoin(string({records.sha256}), '|');
    snapshot.rois(i) = struct( ...
        'roi_index', indices(i), ...
        'roi_id', id, ...
        'source_path', normalizedPath(source.path), ...
        'roi_bbox', double(source.value), ...
        'files', records, ...
        'source_sha256', textSha256(aggregate), ...
        'image_store_sha256', records(1).sha256);
end
end

