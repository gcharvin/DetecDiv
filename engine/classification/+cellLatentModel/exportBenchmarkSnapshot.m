function result = exportBenchmarkSnapshot(classif, split, exportId, varargin)
%CELLLATENTMODEL.EXPORTBENCHMARKSNAPSHOT Freeze leak-free external eval data.
%
% This exporter deliberately produces two physically separate contracts:
%   inputs/inputs_manifest.json   inference-only raw images and frame-local
%                                 instance masks;
%   targets/targets_manifest.json scoring-only reviewed stable identities,
%                                 lifecycle events and parent/NULL labels.
%
% The top-level manifest links both contracts, their hashes, the immutable
% DetecDiv sources, the exact split and annotation approvals.  Nothing is
% written back to the classifier or its ROIs.

p = inputParser;
p.addParameter('ExternalRoot', ...
    'C:\Users\Gilles\SynologyDrive\Data\cell_latent_model', ...
    @(x) ischar(x) || isstring(x));
p.addParameter('InputMaskChannel', trainingText(classif, ...
    'instanceChannelName', ''), @(x) ischar(x) || isstring(x));
p.addParameter('BrightfieldChannel', trainingText(classif, ...
    'brightfieldChannelName', ''), @(x) ischar(x) || isstring(x));
p.addParameter('GroundTruthMaskChannel', trainingText(classif, ...
    'trackChannelName', ''), @(x) ischar(x) || isstring(x));
p.addParameter('GroundTruthFamily', trainingText(classif, ...
    'groundTruthFamily', ''), @(x) ischar(x) || isstring(x));
p.addParameter('Domain', trainingText(classif, ...
    'trainingDomain', 'detecdiv'), @(x) ischar(x) || isstring(x));
p.addParameter('LabelQuality', 'human_ground_truth', ...
    @(x) ischar(x) || isstring(x));
p.addParameter('Supersedes', '', @(x) ischar(x) || isstring(x));
p.addParameter('KnownExclusions', {}, @isTextCollection);
p.addParameter('AuditWarnings', {}, @isTextCollection);
% Unit tests are the only supported exception to the backed-up data root.
p.addParameter('AllowUnitTestRoot', false, ...
    @(x) islogical(x) && isscalar(x));
p.parse(varargin{:});
opts = p.Results;

exportId = validatedExportId(exportId);
externalRoot = canonicalPath(opts.ExternalRoot);
assertAllowedRoot(externalRoot, opts.AllowUnitTestRoot);
unitTestMode = opts.AllowUnitTestRoot && ...
    isPathWithin(externalRoot, canonicalPath(tempdir));
experimentsRoot = fullfile(externalRoot, 'experiments');
if ~isfolder(experimentsRoot), mkdir(experimentsRoot); end
experimentsRoot = canonicalPath(experimentsRoot);
if ~isPathWithin(experimentsRoot, externalRoot)
    error('cellLatentModel:BenchmarkPathEscapesRoot', ...
        'Experiments directory resolves outside the approved external root.');
end
finalDir = fullfile(experimentsRoot, exportId);
if isfolder(finalDir) || isfile(finalDir)
    error('cellLatentModel:ImmutableBenchmarkExists', ...
        ['Benchmark snapshot "%s" already exists. Completed snapshots ' ...
         'are immutable; choose the next vNNN export ID.'], finalDir);
end
stageDir = fullfile(experimentsRoot, sprintf('.%s.staging_%s', ...
    exportId, compactUuid()));
if isfolder(stageDir) || isfile(stageDir)
    error('cellLatentModel:BenchmarkStagingCollision', ...
        'Benchmark staging target already exists: %s', stageDir);
end

splitContract = normalizeSplit(classif, split);
roiIndices = [splitContract.train_indices, ...
    splitContract.validation_indices, splitContract.test_indices];
if isempty(roiIndices)
    error('cellLatentModel:EmptyBenchmarkSplit', ...
        'At least one ROI must be assigned to train, validation or test.');
end

inputMaskName = requiredText(opts.InputMaskChannel, ...
    'InputMaskChannel');
brightfieldName = requiredText(opts.BrightfieldChannel, ...
    'BrightfieldChannel');
gtMaskName = requiredText(opts.GroundTruthMaskChannel, ...
    'GroundTruthMaskChannel');
gtFamilyName = requiredText(opts.GroundTruthFamily, ...
    'GroundTruthFamily');
if strcmpi(inputMaskName, gtMaskName)
    error('cellLatentModel:BenchmarkInputTargetCollision', ...
        ['Inference masks "%s" are also the reviewed GT mask provider. ' ...
         'Select a distinct frame-local prediction/segmentation channel; ' ...
         'reviewed spatial masks must never enter the inference bundle.'], ...
        inputMaskName);
end
if strcmpi(brightfieldName, gtMaskName)
    error('cellLatentModel:BenchmarkInputTargetCollision', ...
        ['Brightfield input "%s" is also the reviewed GT mask provider. ' ...
         'Select a genuine raw image channel; reviewed labels must never ' ...
         'enter the inference bundle through a raw-image binding.'], ...
        brightfieldName);
end
if strcmpi(brightfieldName, inputMaskName)
    error('cellLatentModel:BenchmarkInputRoleCollision', ...
        ['Brightfield "%s" and frame-local masks must be distinct source ' ...
         'channels.'], brightfieldName);
end
assertSafeInputChannelName(inputMaskName, 'InputMaskChannel');
assertSafeInputChannelName(brightfieldName, 'BrightfieldChannel');
labelQuality = validatedLabelQuality(opts.LabelQuality);

approvals = cellLatentModel.assertGroundTruthReady(classif, roiIndices);
if numel(approvals) ~= numel(roiIndices) || ...
        any(strlength(string({approvals.approved_hash})) ~= 64)
    error('cellLatentModel:BenchmarkRequiresManagedApproval', ...
        ['Every exported ROI must have a current managed DetecDiv GT ' ...
         'approval. Legacy or unhashed GT cannot be frozen for scoring.']);
end

sourceBefore = sourceSnapshot(classif, roiIndices);
assertUniqueSourcePayloads(sourceBefore);
assertClassifierSnapshotMatches(classif, roiIndices, ...
    sourceBefore.classifier_files.path);
[repoRoot, gitCommit, worktreeStatus] = codeProvenance();
if ~unitTestMode && ~isempty(strtrim(worktreeStatus))
    error('cellLatentModel:BenchmarkDirtyCode', ...
        ['DetecDiv has uncommitted code changes. Commit or restore them ' ...
         'before creating a scientific benchmark snapshot.']);
end
createdAt = utcIso8601();
mkdir(stageDir);
stageCleanup = onCleanup(@() removeFolder(stageDir));
inputsDir = fullfile(stageDir, 'inputs');
targetsDir = fullfile(stageDir, 'targets');
mkdir(inputsDir);
mkdir(targetsDir);

inputRows = repmat(emptyInputRow(), numel(roiIndices), 1);
targetRows = repmat(emptyTargetRow(), numel(roiIndices), 1);
for i = 1:numel(roiIndices)
    roiIndex = roiIndices(i);
    roiObj = detachedDiskRoi(classif.roi(roiIndex), ...
        {inputMaskName, brightfieldName, gtMaskName});
    assertInputChannelRoles(roiObj, inputMaskName, brightfieldName);
    approval = approvalForIndex(approvals, roiIndex);
    frames = approvedFrames(approval, roiObj);
    partition = partitionForIndex(splitContract, roiIndex);

    inputMasks = readSinglePlaneStack(roiObj, inputMaskName, true);
    brightfield = readSinglePlaneStack(roiObj, brightfieldName, false);
    gtMaskLabels = readSinglePlaneStack(roiObj, gtMaskName, true);
    assertCompatibleStacks(inputMasks, brightfield, gtMaskLabels, ...
        roiObj.id);
    assertFramesAvailable(frames, size(inputMasks, 3), roiObj.id);
    inputMasks = canonicalFrameLocalLabels(inputMasks(:,:,frames));
    brightfield = single(brightfield(:,:,frames));
    gtMaskLabels = uint32(gtMaskLabels(:,:,frames));

    [model, ~] = roiObj.loadCellModel('MigrateLegacy', true);
    assertInferenceChannelsNotGroundTruth( ...
        model, inputMaskName, brightfieldName, roiObj.id);

    inputRel = sprintf('inputs/roi_%03d_inputs.h5', roiIndex);
    inputFile = fullfile(stageDir, strrep(inputRel, '/', filesep));
    writeStack(inputFile, '/frame_local_instance_masks', ...
        inputMasks, 'uint32');
    writeStack(inputFile, '/brightfield', brightfield, 'single');
    inputHash = fileSha256(inputFile);

    [stableIds, family] = cellLatentTracker.materializeStableTracks( ...
        gtMaskLabels, model, frames, gtMaskName);
    assertGroundTruthFamily(family, gtFamilyName, roiObj.id);
    parentage = annotationManager.validateParentage( ...
        model, family.family_id, 'Frames', frames);
    if ~parentage.valid
        error('cellLatentModel:InvalidBenchmarkParentage', ...
            'ROI %s has invalid reviewed parentage: %s', ...
            char(string(roiObj.id)), ...
            strjoin(cellstr(parentage.errors), ' '));
    end
    target = buildTargets(model, family, stableIds, frames, ...
        annotationManager.frameCount(roiObj), roiObj.id, ...
        approval.approved_hash);
    targetRel = sprintf('targets/roi_%03d_targets.h5', roiIndex);
    targetFile = fullfile(stageDir, strrep(targetRel, '/', filesep));
    writeTargetFile(targetFile, stableIds, target);
    targetHash = fileSha256(targetFile);

    inputRows(i) = struct( ...
        'roi_id', char(string(roiObj.id)), ...
        'partition', partition, ...
        'source_frames', frames, ...
        'frame_bounds', [frames(1) frames(end)], ...
        'payload_path', inputRel, ...
        'payload_sha256', inputHash, ...
        'payload_bytes', fileBytes(inputFile), ...
        'mask_channel', inputMaskName, ...
        'mask_dataset', '/frame_local_instance_masks', ...
        'mask_representation', 'canonical_frame_local_labels', ...
        'brightfield_channel', brightfieldName, ...
        'brightfield_dataset', '/brightfield');
    targetRows(i) = struct( ...
        'roi_id', char(string(roiObj.id)), ...
        'partition', partition, ...
        'source_frames', frames, ...
        'frame_bounds', [frames(1) frames(end)], ...
        'payload_path', targetRel, ...
        'payload_sha256', targetHash, ...
        'payload_bytes', fileBytes(targetFile), ...
        'relation_namespace', target.relation_namespace, ...
        'stable_id_dataset', '/stable_track_ids', ...
        'lifecycle_datasets', target.lifecycle_datasets, ...
        'relation_datasets', target.relation_datasets, ...
        'track_count', numel(target.track_ids), ...
        'parent_count', nnz(target.birth_class == uint8(2)), ...
        'null_count', nnz(target.birth_class == uint8(1)), ...
        'end_count', nnz(target.end_observed), ...
        'approval', approvalRecord(approval), ...
        'label_quality', labelQuality);
end

inputsManifest = struct( ...
    'schema_version', 1, ...
    'format', 'detecdiv_benchmark_inputs_v1', ...
    'export_id', exportId, ...
    'creation_time_utc', createdAt, ...
    'source_system', 'DetecDiv', ...
    'source_classifier', inferenceClassifierProvenance( ...
        classif, sourceBefore.classifier_files), ...
    'source_rois', inferenceRoiProvenance(sourceBefore.rois), ...
    'code', struct( ...
        'repository_id', 'DetecDiv', ...
        'repository_path_sha256', textSha256(normalizedPath(repoRoot)), ...
        'git_commit', gitCommit, ...
        'worktree_clean', isempty(strtrim(worktreeStatus)), ...
        'worktree_status_sha256', textSha256(worktreeStatus)), ...
    'contract', ['Inference-only BF/raw pixels and independently relabeled ' ...
        'frame-local instance masks. No reviewed annotations are present.'], ...
    'domain', char(string(opts.Domain)), ...
    'split', inputSplit(splitContract), ...
    'items', inputRows, ...
    'known_exclusions', {{'reviewed annotations', ...
        'persistent object IDs', 'family links', 'scoring events'}});
assertInferenceManifestClean(inputsManifest);
inputsManifestFile = fullfile(inputsDir, 'inputs_manifest.json');
writeJsonNew(inputsManifestFile, inputsManifest);
assertInferenceDirectoryClean(inputsDir);

parentagePolicy = parentageEventPolicy();
targetsManifest = struct( ...
    'schema_version', 1, ...
    'format', 'detecdiv_benchmark_targets_v1', ...
    'contract', ['Scoring-only human-reviewed stable identities, observed ' ...
        'birth/END events and mother/NULL parentage. Never load this ' ...
        'manifest during inference.'], ...
    'first_frame_policy', ...
        'NULL unless an explicit reviewed mother relation exists', ...
    'parentage_event_policy', parentagePolicy, ...
    'domain', char(string(opts.Domain)), ...
    'label_quality', labelQuality, ...
    'split', targetSplit(splitContract), ...
    'items', targetRows);
targetsManifestFile = fullfile(targetsDir, 'targets_manifest.json');
writeJsonNew(targetsManifestFile, targetsManifest);

sourceAfter = sourceSnapshot(classif, roiIndices);
assertSnapshotsEqual(sourceBefore, sourceAfter);
inputsRecord = manifestRecord(inputsManifestFile, stageDir);
targetsRecord = manifestRecord(targetsManifestFile, stageDir);
topManifest = struct( ...
    'schema_version', 1, ...
    'format', 'detecdiv_external_benchmark_snapshot_v1', ...
    'export_id', exportId, ...
    'creation_time_utc', createdAt, ...
    'supersedes', char(string(opts.Supersedes)), ...
    'source_system', 'DetecDiv', ...
    'source_classifier', struct( ...
        'id', char(string(classif.strid)), ...
        'path', normalizedPath(classif.path), ...
        'files', sourceBefore.classifier_files), ...
    'source_rois', sourceBefore.rois, ...
    'code', struct('repository', normalizedPath(repoRoot), ...
        'git_commit', gitCommit, 'worktree_status', worktreeStatus), ...
    'split_contract', topSplit(splitContract), ...
    'label_contract', struct( ...
        'quality', labelQuality, ...
        'authority', 'DetecDiv managed human-reviewed GT', ...
        'first_frame_policy', ...
            'NULL unless explicitly mother-linked by the reviewer', ...
        'parentage_event_policy', parentagePolicy, ...
        'inference_target_separation', 'physical_manifests_and_payloads'), ...
    'inputs_manifest', inputsRecord, ...
    'targets_manifest', targetsRecord, ...
    'known_exclusions', {textCollection(opts.KnownExclusions)}, ...
    'audit_warnings', {unique([textCollection(opts.AuditWarnings), ...
        dirtyWarning(worktreeStatus)], 'stable')});
topManifestFile = fullfile(stageDir, 'manifest.json');
writeJsonNew(topManifestFile, topManifest);

% Re-read every manifest and verify every declared hash before publication.
jsondecode(fileread(inputsManifestFile));
jsondecode(fileread(targetsManifestFile));
jsondecode(fileread(topManifestFile));
verifyPayloadRecords(stageDir, inputRows, targetRows);
assertSnapshotsEqual(sourceBefore, sourceSnapshot(classif, roiIndices));
cellLatentModel.utils.atomicPublishDirectory(stageDir, finalDir);
clear stageCleanup;

result = struct( ...
    'directory', finalDir, ...
    'manifest', fullfile(finalDir, 'manifest.json'), ...
    'inputs_manifest', fullfile(finalDir, 'inputs', ...
        'inputs_manifest.json'), ...
    'targets_manifest', fullfile(finalDir, 'targets', ...
        'targets_manifest.json'), ...
    'export_id', exportId);
end

