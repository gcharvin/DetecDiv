files = files(~[files.isdir]);
for i = 1:numel(files)
    [~, name, ext] = fileparts(files(i).name);
    assertNoForbiddenToken([name ext], inputForbiddenTokens(), folder);
    filename = fullfile(files(i).folder, files(i).name);
    if strcmpi(ext, '.json')
        assertInferenceManifestClean(jsondecode(fileread(filename)));
    elseif any(strcmpi(ext, {'.h5','.hdf5'}))
        scanH5Names(h5info(filename), inputForbiddenTokens(), filename);
    else
        error('cellLatentModel:BenchmarkInputLeakage', ...
            'Unsupported file in inference directory: %s', filename);
    end
end
end

