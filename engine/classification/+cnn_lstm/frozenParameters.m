function p = frozenParameters(c,ctx)
%FROZENPARAMETERS Keep image bindings separate from temporal optimizer options.
if nargin<2,ctx=struct();end
t=c.trainingParam;if isfield(ctx,'params'),t=cnn_lstm.utils.applyParamOverrides(t,ctx.params);end
assert(~t.train_CNN_classifier,'cnn_lstm:FrozenBackbone','Frozen encoder mode cannot train the CNN.');
assert(strcmp(pick(t.classifier_output),'sequence-to-one'),'cnn_lstm:FrozenMode','Frozen encoder head requires sequence-to-one.');
p=struct('featureCount',1024,'outputMode','window','windowLength',t.LSTM_sequence_length, ...
 'hiddenUnits',t.LSTM_hidden_size,'maxEpochs',t.LSTM_max_epochs, ...
 'miniBatchSize',t.LSTM_mini_batch_size,'initialLearnRate',t.LSTM_initial_learning_rate, ...
 'dropout',t.LSTM_dropout,'l2Regularization',t.LSTM_l2_regularization, ...
 'classWeighting',pick(t.LSTM_class_weighting),'validationPatience',t.LSTM_validation_patience, ...
 'returnBestValidation',t.LSTM_return_best_validation,'seed',t.Format_Seed, ...
 'missingPolicy','error','executionEnvironment',pick(t.execution_environment), ...
 'encoderLayer',t.frozen_encoder_layer);
assert(p.windowLength>0&&p.windowLength==fix(p.windowLength),'cnn_lstm:Window','Choose a positive integer window length.');
assert(p.hiddenUnits>=1&&p.dropout>=0&&p.dropout<1&&p.l2Regularization>=0,'cnn_lstm:Parameters','Invalid temporal-head parameters.');
end
function value=pick(value)
while iscell(value),value=value{end};end
value=char(string(value));
end
