function testAllPackagedClassifierContractsReceiveRequiredChannels(testCase)
packages = {'budMotherLinker','cellLatentModel','cellLatentTracker', ...
    'cellposesam','cnn','cnn_lstm', ...
    'deeplab_pixel_classification','sam31','trackastra'};
for p = 1:numel(packages)
    pkg = packages{p};
    params = struct('pkg', pkg);
    if strcmp(pkg, 'cellLatentModel')
        params.backend = 'continuous_cell_state';
    end
    contract = pipelineNodeContract(struct( ...
        'type', 'classifier', 'pkg', pkg, ...
        'func', [pkg '.classify'], 'params', params));
    requiredKeys = requiredContractChannelKeys(contract);
    stored = arrayfun(@(i)sprintf('%s_input_%d', pkg, i), ...
        1:max(1, numel(requiredKeys)), 'UniformOutput', false);
    classifier = struct( ...
        'trainingParam', struct(), 'executionParam', struct(), ...
        'channelName', {stored}, 'channelName2', '', ...
        'dataset', struct('channels', {{}}));

    actual = classifierApplyPipelineInputBindings( ...
        struct(), classifier, contract, 'validate', '');

    for k = 1:numel(requiredKeys)
        key = requiredKeys{k};
        verifyTrue(testCase, isfield(actual, key), ...
            sprintf('%s did not configure required selector %s.', pkg, key));
        verifyNotEmpty(testCase, actual.(key), ...
            sprintf('%s left required selector %s empty.', pkg, key));
    end
end
end


