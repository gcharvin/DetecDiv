function contract = channelContract(selectorKeys, requiredKeys)
contract = struct();
contract.binding = struct('selectorKeys', {selectorKeys});
resources = repmat(struct( ...
    'type', 'channel', 'required', false, 'param', '', 'nameParam', ''), ...
    1, numel(selectorKeys));
for i = 1:numel(selectorKeys)
    resources(i).param = selectorKeys{i};
    resources(i).nameParam = selectorKeys{i};
    resources(i).required = any(strcmp(requiredKeys, selectorKeys{i}));
end
contract.resources = struct('in', resources);
end

function keys = requiredContractChannelKeys(contract)
keys = {};
resources = contract.resources.in;
for i = 1:numel(resources)
    if strcmpi(char(string(resources(i).type)), 'channel') && ...
            logical(resources(i).required)
        key = char(string(resources(i).param));
        if ~isempty(key)
            keys{end+1} = key; %#ok<AGROW>
        end
    end
end
keys = unique(keys, 'stable');
end

